private val iso639LanguageReverseMapping = iso639LanguageMapping.entries.associate { (k, v) -> v to k }

fun getLanguageISO639v2Value(language: KeyValue): String {
    if (language.key == null) {
        return language.value
            ?: throw ServerException.withReason("Could not map document language: $language")
    }
    return iso639LanguageReverseMapping[language.key]
        ?: throw ServerException.withReason("Could not map document language key: ${language.key}")
}

fun getISO3166v1Alpha3FromNumericLanguageCode(language: KeyValue): String {
    if (language.key == null) {
        return language.value
            ?: throw ServerException.withReason("Could not map document language: $language")
    }
    return iso3166Alpha3Mapping[language.key]
        ?: throw ServerException.withReason("Could not map document language key: ${language.key}")
}
